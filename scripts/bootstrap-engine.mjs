import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {existsSync} from 'node:fs';
import {copyFile,mkdir,mkdtemp,readFile,rename,rm,writeFile} from 'node:fs/promises';
import {basename,join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {run,root,pnpm} from './process.mjs';

const args=process.argv.slice(2).filter(value=>value!=='--');
let artifacts,source,offline=false;
while(args.length){const flag=args.shift();if(flag==='--artifacts'||flag==='--source'){const value=args.shift();if(!value||value.startsWith('--'))throw new Error(`${flag} requires a directory.`);if(flag==='--artifacts')artifacts=resolve(value);else source=resolve(value);}else if(flag==='--offline')offline=true;else throw new Error(`Unknown option: ${flag}`);}
if(artifacts&&source)throw new Error('Use only one of --artifacts or --source.');
const engine=JSON.parse(await readFile(join(root,'engine-source.json'),'utf8'));
let temporaryOutput;
try {
if(!artifacts){
  if(!source){
    assert.match(engine.ref,/^[0-9a-f]{40}$/,'Default bootstrap requires a pinned engine commit.');
    source=join(root,'.engine-source');
    if(offline)throw new Error('Offline bootstrap requires --artifacts or an existing --source checkout.');
    const fresh=!existsSync(source);
    if(fresh)await run('git',['clone','--no-checkout','--depth','1',engine.repository,source]);
    const remote=(await run('git',['remote','get-url','origin'],{cwd:source,capture:true})).trim();
    assert.equal(remote,engine.repository,'Scratch checkout has an unexpected origin.');
    const changes=await run('git',['status','--porcelain','--untracked-files=no'],{cwd:source,capture:true});
    if(!fresh&&changes.trim())throw new Error('The engine scratch checkout has tracked changes; preserve them before bootstrapping.');
    await run('git',['fetch','--depth','1','origin',engine.ref],{cwd:source});
    await run('git',['checkout','--detach','FETCH_HEAD'],{cwd:source});
  }
  await run(pnpm,['install','--frozen-lockfile',...(offline?['--offline']:[])],{cwd:source});
  await run(pnpm,['clean'],{cwd:source});
  await run(pnpm,['build:all'],{cwd:source});
  temporaryOutput=await mkdtemp(join(tmpdir(),'xecms-builder-engine-pack-'));
  artifacts=join(temporaryOutput,'release');
  await run(pnpm,['release:pack','--output',artifacts],{cwd:source});
}
const manifest=JSON.parse(await readFile(join(artifacts,'release-manifest.json'),'utf8'));
assert.equal(manifest.engineVersion,engine.version,'Engine artifact version does not match the builder contract.');
assert.ok(Array.isArray(manifest.packages)&&manifest.packages.length>0,'Engine packages are missing.');
const localNames=new Set(['@xecms/admin-apps','@xecms/admin-runtime','@xecms/app-builder-client','@xecms/app-builder-server','@xecms/app-builder-admin']);
const pending=join(root,`.engine-artifacts-${process.pid}`),destination=join(root,'.engine-artifacts');
await mkdir(pending,{recursive:true});
const names={};
try{
 for(const item of manifest.packages){
  if(localNames.has(item.name))continue;
  assert.equal(basename(item.filename),item.filename,'Unsafe artifact filename.');
  assert.equal(names[item.name],undefined,'Duplicate engine artifact.');
  const bytes=await readFile(join(artifacts,item.filename));
  assert.equal(createHash('sha512').update(bytes).digest('hex'),item.sha512,`Checksum mismatch: ${item.filename}`);
  const expected=['@xecms/plugin-sdk','@xecms/example-plugin'].includes(item.name)?'2.0.0':engine.version;
  assert.equal(item.version,expected,`Unexpected package version: ${item.name}`);
  await copyFile(join(artifacts,item.filename),join(pending,item.filename));names[item.name]=item.filename;
 }
 for(const name of ['@xecms/server','@xecms/database','@xecms/client','@xecms/contracts','@xecms/schema','@xecms/application','@xecms/admin','@xecms/ui','@xecms/admin-app'])assert.ok(names[name],`Missing engine artifact: ${name}`);
 await writeFile(join(pending,'release-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
 await rm(destination,{recursive:true,force:true});await rename(pending,destination);
 await writeFile(join(root,'.pnpmfile.cjs'),`// Generated by bootstrap-engine.mjs. Local only; never publish this file.\nconst {resolve}=require('node:path');\nconst files=${JSON.stringify(names,null,2)};\nmodule.exports={hooks:{readPackage(pkg){for(const section of ['dependencies','devDependencies','optionalDependencies']){for(const [name,version] of Object.entries(pkg[section]??{})){if(files[name]&&!version.startsWith('workspace:'))pkg[section][name]='file:'+resolve(__dirname,'.engine-artifacts',files[name]);}}return pkg;}}};\n`);
 await run(pnpm,['install','--no-frozen-lockfile',...(offline?['--offline']:[])]);
 console.log(`Installed validated engine ${engine.version} artifacts. Package manifests retain registry versions.`);
}finally{await rm(pending,{recursive:true,force:true});}

} finally {if(temporaryOutput)await rm(temporaryOutput,{recursive:true,force:true});}
